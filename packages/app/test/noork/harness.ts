// Test harness for the Focus Session property tests.
//
// Wires the real controller pieces together exactly the way session-store.ts does
// (controller -> idle monitor -> focus tracker -> timeline), but with the deterministic
// fake clock from the controller folder, so every property runs without real time passing.
import {
  createFocusTracker,
  followFocus,
  workElapsedMs,
} from "../../src/pages/home/focus-session/controller/focus-score"
import { createFocusTimeline } from "../../src/pages/home/focus-session/controller/focus-timeline"
import { createIdleMonitor, followSession } from "../../src/pages/home/focus-session/controller/idle-monitor"
import type { FocusTiming } from "../../src/pages/home/focus-session/controller/presets"
import { createFocusSessionController } from "../../src/pages/home/focus-session/controller/session-controller"
import { createFakeAudio, createFakeClock } from "../../src/pages/home/focus-session/controller/test-fakes"

export const MINUTE = 60_000

// Thresholds taken from the requirement text (R1), NOT imported from idle-monitor.ts.
// If the tests imported the code's own constants, a wrong value in the code (e.g. 2:01
// instead of 2:00) would also change the expected value and no property could catch it.
export const REQ_IDLE_MS = 2 * MINUTE // "no activity for 2 minutes" -> yellow + check-in
export const REQ_RED_AFTER_MS = 60_000 // "unanswered for 60 seconds" -> red

// One user action during a running session. Generated by the arbitraries in arbitraries.ts.
export type SessionAction =
  | { type: "advance"; ms: number } // time passes with no input
  | { type: "activity" } // mouse / keyboard input inside opencode
  | { type: "away" } // the user leaves the opencode tab or window
  | { type: "answer"; needsHelp: boolean } // "Yes, help me" (true) or "No, I'm fine" (false)
  | { type: "pause" }
  | { type: "resume" }

export function createSession() {
  const time = createFakeClock()
  const { audio } = createFakeAudio()
  const controller = createFocusSessionController({ clock: time.clock, audio })
  const monitor = createIdleMonitor({ clock: time.clock })
  followSession(controller, monitor)
  const tracker = createFocusTracker({ clock: time.clock })
  const timeline = createFocusTimeline()
  followFocus(controller, monitor, tracker, timeline)

  const elapsed = () => workElapsedMs(controller.snapshot())

  // Every check-in ("Need help?" pop-up) the monitor fires, with the elapsed work time it fired at.
  const checkIns: number[] = []
  monitor.subscribe((event) => {
    if (event.type === "check-in") checkIns.push(elapsed())
  })

  const apply = (action: SessionAction) => {
    if (action.type === "advance") return time.advance(action.ms)
    if (action.type === "activity") return monitor.activity()
    if (action.type === "away") return monitor.away()
    if (action.type === "answer") return monitor.answer(action.needsHelp)
    if (action.type === "pause") return controller.pause()
    return controller.resume()
  }

  return {
    time,
    controller,
    monitor,
    tracker,
    timeline,
    checkIns,
    elapsed,
    apply,
    start: (timing: FocusTiming) => controller.start({ timing, volume: 1 }),
  }
}

export type Session = ReturnType<typeof createSession>
